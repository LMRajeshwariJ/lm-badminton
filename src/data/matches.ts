const day = "2026-10-09";

function at(time: string) {
  return `${day}T${time}:00+05:30`;
}

function game(home: number, away: number, winner: Side | null): GameScore {
  return { home, away, winner };
}

function createMatch(input: {
  id: string;
  category: CategoryId;
  round: RoundId;
  status: Match["status"];
  homeId: string | null;
  awayId: string | null;
  courtId?: string | null;
  scheduledAt?: string | null;
  games?: GameScore[];
  serving?: Side | null;
  servingPlayerId?: string | null;
  positions?: Match["positions"];
  startedAt?: string | null;
  winnerId?: string | null;
  nextMatchId?: string | null;
  nextSlot?: Side | null;
  timeline?: TimelineEvent[];
}): Match {
  const meta = CATEGORY_META[input.category];
  return {
    id: input.id,
    category: input.category,
    round: input.round,
    status: input.status,
    homeId: input.homeId,
    awayId: input.awayId,
    courtId: input.courtId ?? null,
    scheduledAt: input.scheduledAt ?? null,
    pointsPerGame: meta.pointsPerGame,
    maxPoints: meta.maxPoints,
    bestOf: 3,
    winBy: 2,
    games: input.games ?? [],
    serving: input.serving ?? null,
    servingPlayerId: input.servingPlayerId ?? null,
    positions: input.positions ?? {},
    winnerId: input.winnerId ?? null,
    startedAt: input.startedAt ?? null,
    completedAt: null,
    nextMatchId: input.nextMatchId ?? null,
    nextSlot: input.nextSlot ?? null,
    paused: false,
    timeline: input.timeline ?? [],
    history: [],
  };
}

function resultTimeline(id: string, start: string, lines: string[]): TimelineEvent[] {
  return [
    { id: `${id}-start`, type: "start", text: "Match started", at: start },
    ...lines.map((text, index) => ({
      id: `${id}-note-${index}`,
      type: index === lines.length - 1 ? ("match" as const) : ("game" as const),
      text,
      at: start,
    })),
  ];
}

